package org.wildfly.mcp.example;

import dev.langchain4j.service.AiServiceContext;
import dev.langchain4j.service.tool.ToolArgumentsErrorHandler;
import dev.langchain4j.service.tool.ToolExecutionErrorHandler;
import dev.langchain4j.service.tool.ToolService;
import dev.langchain4j.spi.services.AiServiceContextFactory;

/**
 * Configures tool error handlers explicitly for every AI service.
 * <p>
 * {@code @RegisterAIService} (langchain4j-cdi) does not expose the tool error handlers, so they are
 * set here through the LangChain4j SPI, which {@code AiServices.builder(..)} consults when it creates its context.
 * <ul>
 *   <li>Invalid tool arguments generated by the LLM: the LLM sees the error and can retry with corrected arguments.</li>
 *   <li>Exceptions thrown by a tool (e.g. MCP server failures): the invocation fails, so internal details are not
 *   sent to the LLM, and MicroProfile Fault Tolerance ({@code @Retry}/{@code @Fallback}) handles the failure.
 *   Only exceptions implementing {@code ToolErrorVisibleToLlm} are passed to the LLM.</li>
 * </ul>
 * Registered in {@code META-INF/services/dev.langchain4j.spi.services.AiServiceContextFactory}.
 */
public class ToolErrorHandlingAiServiceContextFactory implements AiServiceContextFactory {

    @Override
    public AiServiceContext create(Class<?> aiServiceClass) {
        AiServiceContext context = new AiServiceContext(aiServiceClass) {
        };
        ToolService toolService = new ToolService();
        toolService.argumentsErrorHandler(ToolArgumentsErrorHandler.sendExceptionMessageToLlm());
        toolService.executionErrorHandler(ToolExecutionErrorHandler.failInvocationUnlessVisibleToLlm());
        context.toolService = toolService;
        return context;
    }
}